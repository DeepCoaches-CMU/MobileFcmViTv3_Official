#!/usr/bin/env python3
"""
generate_report_tables.py

Generates report.tex's result tables directly from the underlying JSON result
files, so table rows can never drift from — or be transcribed incorrectly
from — the actual runs that produced them (this replaces hand-typed tables
that were previously found to have mislabeled/swapped rows: e.g. report.tex's
"FCM-only" row actually contained full_fcm_scratch's number, and "MobileViTv3-
only" contained no_fcm_scratch's number).

Every row's label is derived directly from the result directory name that
produced it — there is no manual name-to-number mapping step where a mistake
could be introduced.

Usage:
    python3 scripts/generate_report_tables.py --output report_tables_generated.tex

Then in report.tex:
    \\input{report_tables_generated}
"""

import argparse
import json
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent

# ablation_results/mobilefcmvitv3_<suffix> -> display name
ABLATION_DISPLAY_NAMES = {
    'full_fcm_pretrained':      'Full FCM + Pretrained',
    'full_fcm_scratch':         'Full FCM, No Pretrained (Scratch)',
    'full_fcm_no_mixup':        'Full FCM, No Mixup',
    'full_fcm_no_classweights': 'Full FCM, No Class Weights',
    'full_fcm_no_smoothing':    'Full FCM, No Label Smoothing',
    'full_fcm_dropout_0.3':     'Full FCM, Dropout 0.3',
    'no_fcm_pretrained':        'No FCM (MobileFCMViT arch, FCM losses off), Pretrained',
    'no_fcm_scratch':           'No FCM (MobileFCMViT arch, FCM losses off), Scratch',
    'fcm_only':                 'FCM-Only (no backbone)',
    'mobilevitv3_only':         'MobileViTv3-Only (no FCM module)',
}


def load_json(path):
    if not path.exists():
        return None
    with open(path) as f:
        return json.load(f)


def latex_escape(s):
    return s.replace('_', '\\_').replace('%', '\\%')


def build_ablation_table():
    rows = []
    for suffix, display in ABLATION_DISPLAY_NAMES.items():
        result_dir = REPO_ROOT / 'ablation_results' / f'mobilefcmvitv3_{suffix}' / 'results'
        record = load_json(result_dir / 'best_metrics.json')
        if record is None:
            rows.append((display, None, str(result_dir)))
            continue
        rows.append((display, record['val_top1'], None))

    lines = [
        '% Auto-generated by scripts/generate_report_tables.py — do not hand-edit.',
        '\\begin{tabular}{l|c}',
        '\\textbf{Model} & \\textbf{Top-1 Accuracy (\\%)} \\\\',
        '\\hline',
    ]
    missing = []
    for display, top1, missing_path in rows:
        if top1 is None:
            lines.append(f'{latex_escape(display)} & -- (not yet run) \\\\')
            missing.append(missing_path)
        else:
            lines.append(f'{latex_escape(display)} & {top1:.2f} \\\\')
    lines.append('\\end{tabular}')

    if missing:
        print("WARNING: missing ablation results (not included as real numbers):")
        for m in missing:
            print(f"  - {m}")

    return '\n'.join(lines)


# The original 6-config tuning sweep predates the 2026-07 dataset-split
# rebuild (scripts/build_busi_split.py). Any of these NOT in the set below
# still reflects the old, non-deduped, train/validation-only split and gets
# flagged "old split — pending rerun". Any config outside this original set
# (e.g. tune_07+) was created after the rebuild and is current by default —
# no ongoing bookkeeping needed for new configs, only for backfilling these six.
ORIGINAL_SIX = {
    'tune_01_lr_aug', 'tune_02_extend', 'tune_03_seed2',
    'tune_04_focal', 'tune_05_augmix', 'tune_06_regdrop',
}
# (tune_06_regdrop trains on datasets2/BUS-UCLM, not datasets/BUSI_split — it's
# "refreshed" in the sense that its tune_01 warm-start checkpoint is current,
# but still flagged separately below as not directly comparable.)
REFRESHED_ON_CURRENT_SPLIT = {
    'tune_01_lr_aug', 'tune_02_extend', 'tune_03_seed2', 'tune_04_focal',
    'tune_05_augmix', 'tune_06_regdrop',
}

# Directories that aren't independent tuning candidates: archived pre-rebuild
# results (kept for provenance) and per-seed variance reruns (reported
# separately in the Seed Variance table, not as their own rows here). A
# directory only counts as a real tuning config if it has its own YAML —
# derived variants (e.g. tune_05_seed42) are launched via CLI override on top
# of another config's YAML and never get one of their own. Do NOT match on
# name pattern alone (e.g. "_seed\d+$") — tune_03_seed2 is a genuine original
# tuning config despite superficially looking like a seed-variant name.
_ARCHIVE_SUFFIX = '_oldsplit'


def build_tuning_table():
    tuning_dir = REPO_ROOT / 'tuning'
    rows = []
    skipped_archived = []
    skipped_no_own_config = []
    for cfg_dir in sorted(tuning_dir.iterdir()):
        if not cfg_dir.is_dir():
            continue
        if cfg_dir.name.endswith(_ARCHIVE_SUFFIX):
            skipped_archived.append(cfg_dir.name)
            continue
        cfg_path = tuning_dir / f'{cfg_dir.name}.yaml'
        if not cfg_path.exists():
            skipped_no_own_config.append(cfg_dir.name)
            continue
        record = load_json(cfg_dir / 'results' / 'best_metrics.json')
        if record is None:
            continue
        notes = []
        try:
            cfg = yaml.safe_load(cfg_path.read_text()) or {}
        except yaml.YAMLError as e:
            print(f"WARNING: could not parse {cfg_path} ({e}); skipping its data_dirs check")
            cfg = {}
        data_dirs = cfg.get('data_dirs') or []
        if any('datasets2' in d for d in data_dirs) and not any(
            d.strip('/').split('/')[0] == 'datasets' for d in data_dirs
        ):
            notes.append('datasets2 — not directly comparable')
        if cfg_dir.name in ORIGINAL_SIX and cfg_dir.name not in REFRESHED_ON_CURRENT_SPLIT:
            notes.append('old split — pending rerun')
        note = f" ({'; '.join(notes)})" if notes else ''
        rows.append((cfg_dir.name, record['val_top1'], note))

    if skipped_archived:
        print(f"Tuning table: excluded {len(skipped_archived)} archived pre-rebuild dir(s): {skipped_archived}")
    if skipped_no_own_config:
        print(f"Tuning table: excluded {len(skipped_no_own_config)} dir(s) with no dedicated config "
              f"(derived variants, e.g. seed reruns — see Seed Variance table): {skipped_no_own_config}")

    lines = [
        '% Auto-generated by scripts/generate_report_tables.py — do not hand-edit.',
        '\\begin{tabular}{l|c}',
        '\\textbf{Tuning Run} & \\textbf{Top-1 Accuracy (\\%)} \\\\',
        '\\hline',
    ]
    for name, top1, note in rows:
        lines.append(f'{latex_escape(name)}{latex_escape(note)} & {top1:.2f} \\\\')
    lines.append('\\end{tabular}')
    return '\n'.join(lines)


def build_aggregate_summary_table(summary_path, unit_label='seed'):
    """Renders an aggregate_seeds.py-format JSON (n_seeds/sources/metrics) as a
    table. Format-agnostic — works the same for seed reruns or k-fold results,
    since both are produced by the same aggregate_seeds.py script."""
    summary = load_json(Path(summary_path)) if summary_path else None
    if summary is None:
        return None
    lines = [
        '% Auto-generated by scripts/generate_report_tables.py — do not hand-edit.',
        f"% Aggregated over {summary['n_seeds']} {unit_label} run(s): {', '.join(summary['sources'])}",
        '\\begin{tabular}{l|c}',
        '\\textbf{Metric} & \\textbf{Mean $\\pm$ Std} \\\\',
        '\\hline',
    ]
    for key, stats in summary['metrics'].items():
        lines.append(f"{latex_escape(key)} & {stats['mean']:.4f} $\\pm$ {stats['std']:.4f} \\\\")
    lines.append('\\end{tabular}')
    return '\n'.join(lines)


def build_test_table():
    """Real held-out test-set numbers (test_results/*/test_metrics_test.json),
    kept separate from validation numbers used for checkpoint selection."""
    test_dir = REPO_ROOT / 'test_results'
    rows = []
    if test_dir.exists():
        for run_dir in sorted(test_dir.iterdir()):
            if not run_dir.is_dir():
                continue
            record = load_json(run_dir / 'test_metrics_test.json')
            if record is None:
                continue
            rows.append((run_dir.name, record))

    lines = [
        '% Auto-generated by scripts/generate_report_tables.py — do not hand-edit.',
        '% Held-out TEST split — never used for checkpoint selection.',
        '\\begin{tabular}{l|c|c|c|c|c|c}',
        'Run & Top-1 & Prec (macro) & Recall (macro) & F1 (macro) & ROC-AUC & PR-AUC \\\\',
        '\\hline',
    ]
    for name, r in rows:
        lines.append(
            f"{latex_escape(name)} & {r['top1']:.2f} & {r['precision_macro']:.4f} & "
            f"{r['recall_macro']:.4f} & {r['f1_macro']:.4f} & {r['roc_auc_macro']:.4f} & "
            f"{r['pr_auc_macro']:.4f} \\\\"
        )
    lines.append('\\end{tabular}')
    if not rows:
        print("WARNING: no test_results/*/test_metrics_test.json found — "
              "run test.py --split test after rebuilding the dataset (Phase 1).")
    return '\n'.join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--output', type=str, default='report_tables_generated.tex')
    p.add_argument('--seed_summary', type=str, default='',
                   help='Optional path to a seed-aggregation JSON from aggregate_seeds.py')
    p.add_argument('--kfold_summary', type=str, default='',
                   help='Optional path to a k-fold-aggregation JSON from aggregate_seeds.py')
    args = p.parse_args()

    sections = [
        '% ==================================================================\n'
        '% Auto-generated tables. Regenerate with:\n'
        '%   python3 scripts/generate_report_tables.py\n'
        '% Do not hand-edit — edits will be overwritten.\n'
        '% ==================================================================\n',
        '\\subsection*{Ablation Results (Validation Top-1 Accuracy)}',
        build_ablation_table(),
        '',
        '\\subsection*{Tuning Runs (Validation Top-1 Accuracy)}',
        build_tuning_table(),
        '',
        '\\subsection*{Held-Out Test Set Results}',
        build_test_table(),
    ]

    seed_table = build_aggregate_summary_table(args.seed_summary, 'seed') if args.seed_summary else None
    if seed_table:
        sections += ['', '\\subsection*{Seed Variance (Mean $\\pm$ Std)}', seed_table]

    kfold_table = build_aggregate_summary_table(args.kfold_summary, 'fold') if args.kfold_summary else None
    if kfold_table:
        sections += ['', '\\subsection*{K-Fold Cross-Validation (Mean $\\pm$ Std)}', kfold_table]

    out_path = REPO_ROOT / args.output
    out_path.write_text('\n'.join(sections) + '\n')
    print(f"\nWrote {out_path}")


if __name__ == '__main__':
    main()
